    function fmtCode(code, v) {
      if(typeof v==='string')return v;
      // 枚举类属性优先查术语表（拍摄模式/白平衡/对焦模式/录制格式等）
      const vm = VALUE_MAP[code];
      if (vm && vm[v] !== undefined) return vm[v];
      const meta = PROP_META[code];
      const f = meta ? meta[2] : 'raw';
      switch (f) {
        case 'fn': return (v <= 0 || v > 5000) ? '--' : ('F' + (v / 100));
        case 'sh': {
          // 官方编码：高16位=分子，低16位=分母（0x000103E8 = 1/1000；0x000F000A = 1.5"）
          if (v === 0) return 'BULB';
          if (v === 0xFFFFFFFF) return '--';
          const num = (v >>> 16) & 0xFFFF, den = v & 0xFFFF;
          if (num === 0 || den === 0) return '--';
          if (num === 1) return '1/' + den;
          if (den === 10) return (num / 10).toFixed(1).replace(/\.0$/, '') + '"';
          return num + '/' + den;
        }
        case 'ang': return (v <= 0 || v > 360000) ? '--' : ((v / 1000) + '°');
        case 'k': return (v < 1500 || v > 20000) ? '--' : (v + 'K');
        case 'db': return v + ' dB';
        case 'zoom': return (v <= 0 || v > 100000) ? '--' : ((v / 100).toFixed(2) + 'x');
        case 'iso': {
          const iso = v & 0xFFFFFF;   // bit0-23=ISO 值，bit24-27=模式，0xFFFFFF=AUTO
          return iso === 0xFFFFFF ? 'AUTO' : ('ISO ' + iso);
        }
        default: return String(v);
      }
    }
